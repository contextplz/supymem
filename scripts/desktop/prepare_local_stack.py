def installation_digest(directory: Path) -> str:
    """Discard generated bytecode so only verified files determine cache identity."""
    for bytecode in directory.rglob("__pycache__"):
        if bytecode.is_symlink():
            bytecode.unlink()
        elif bytecode.is_dir():
            shutil.rmtree(bytecode)
    digest = hashlib.sha256()
    for path in sorted(directory.rglob("*")):
        digest.update(path.relative_to(directory).as_posix().encode())
        digest.update(b"\0")
        if path.is_symlink():
            digest.update(os.readlink(path).encode())
        elif path.is_file():
            with path.open("rb") as stream:
                digest.update(hashlib.file_digest(stream, "sha256").digest())
        digest.update(b"\0")
    return digest.hexdigest()


def standalone_python(target: str) -> Path:
    if target not in {"aarch64-apple-darwin", "x86_64-apple-darwin", "x86_64-unknown-linux-gnu",
                      "aarch64-unknown-linux-gnu", "x86_64-pc-windows-msvc"}:
        raise SystemExit(f"Your Python runtime does not support {target}. Use an arm64 or x64 Mac or Linux computer, or x64 Windows, then rerun ./start.")
    name = f"cpython-{PYTHON_VERSION}+{PYTHON_BUILD}-{target}"
    filename = name + "-install_only_stripped.tar.gz"
    try:
        checksums = dict(line.split(maxsplit=1)[::-1] for line in PYTHON_SHASUMS.read_text().splitlines() if line.strip())
        expected = checksums[filename]
        if not re.fullmatch(r"[a-f0-9]{64}", expected):
            raise ValueError("invalid SHA-256")
    except (OSError, KeyError, ValueError):
        raise SystemExit(f"Your pinned Python checksum for {filename} is missing or invalid. Restore {PYTHON_SHASUMS} from your source release, then rerun ./start.") from None
    cache = python_cache_dir()
    cache.mkdir(parents=True, exist_ok=True, mode=0o700)
    if cache.is_symlink():
        raise SystemExit(f"Your Python cache must be a regular folder. Choose a private cache folder instead of {cache}, then rerun ./start.")
    cache.chmod(0o700)
    archive = cache / filename
    destination = cache / name
    python = destination / "python" / ("python.exe" if "windows" in target else "bin/python3")
    marker = destination / ".archive-digest"
    if archive.is_symlink() or destination.is_symlink():
        raise SystemExit(f"Your Python cache must not use linked archives or folders. Remove {archive} and {destination}, then rerun ./start.")
    with tempfile.TemporaryDirectory(dir=cache) as temporary:
        temporary = Path(temporary)
        download = temporary / filename
        if not archive.is_file():
            print(f"Preparing your standalone Python {PYTHON_VERSION} runtime (about 1 minute on first run).")
            try:
                url = f"https://github.com/astral-sh/python-build-standalone/releases/download/{PYTHON_BUILD}/{filename.replace('+', '%2B')}"
                with urllib.request.urlopen(url, timeout=120) as response, download.open("wb") as output:
                    shutil.copyfileobj(response, output)
            except (OSError, urllib.error.URLError):
                raise SystemExit(f"Your standalone Python runtime is not cached and could not be downloaded. Connect to the internet, then rerun ./start to download {filename}. Your existing work is retained.") from None
        source = archive if archive.is_file() else download
        with source.open("rb") as stream:
            actual = hashlib.file_digest(stream, "sha256").hexdigest()
        if actual != expected:
            raise SystemExit(f"Your Python archive failed SHA-256 verification: {filename} (expected {expected}, got {actual}). Remove {archive} if it exists, then rerun ./start while online.")
        if source == download:
            download.replace(archive)
        if python.is_file() and marker.is_file() and marker.read_text() == expected + ":" + installation_digest(destination / "python"):
            return python
        try:
            with tarfile.open(archive) as distribution:
                distribution.extractall(temporary, filter="data")
            extracted = temporary / "python"
            executable = extracted / python.relative_to(destination / "python")
            if not executable.is_file() or not executable.resolve().is_relative_to(extracted):
                raise ValueError("Python executable is missing or external")
            executable.chmod(0o755)
            if destination.exists():
                shutil.rmtree(destination)
            destination.mkdir()
            shutil.move(str(extracted), destination / "python")
            marker.write_text(expected + ":" + installation_digest(destination / "python"))
        except (OSError, ValueError, tarfile.TarError) as error:
            raise SystemExit(f"Your verified Python archive could not be unpacked: {error}. Close your app, remove {archive} and {destination}, then rerun ./start while online.") from None
    return python


def runtime_identity(binary: Path) -> str:
    binary = binary.resolve()
    try:
        result = subprocess.run([str(binary), "--version"], capture_output=True, text=True, timeout=30, check=True)
        with binary.open("rb") as stream:
            checksum = hashlib.file_digest(stream, "sha256").hexdigest()
    except (OSError, subprocess.SubprocessError):
        raise SystemExit(f"Your runtime at {binary} could not be identified. Run ./start --check to repair your prerequisites, then rerun ./start while online.") from None
    return json.dumps([str(binary), result.stdout.strip() or result.stderr.strip(), checksum])


def ensure_build_python() -> None:
    if sys.version_info[:2] != (3, 12):
        raise SystemExit("Your build needs Python 3.12. Run ./start --check for your install command, then retry.")
    from build_runtime import host_triple

    standalone = standalone_python(host_triple())
    identity = runtime_identity(standalone)
    base = standalone.parent if sys.platform == "win32" else standalone.parent.parent
    environment = ROOT / f".desktop-python-{platform.machine()}"
    marker = environment / ".runtime-identity"
    if (Path(sys.prefix).resolve() == environment.resolve()
            and Path(sys.base_prefix).resolve() == base.resolve()
            and marker.is_file() and marker.read_text() == identity):
        return
    uv = shutil.which("uv")
    python = environment / ("Scripts/python.exe" if sys.platform == "win32" else "bin/python")
    try:
        if environment.exists() and (not marker.is_file() or marker.read_text() != identity):
            shutil.rmtree(environment)
        if not python.is_file():
            command = [uv, "venv", str(environment), "--python", str(standalone)] if uv else [str(standalone), "-m", "venv", str(environment)]
            subprocess.run(command, cwd=ROOT, check=True)
        for lock in ("services/company_os/requirements.runtime.lock", "services/company_os/requirements.build.lock",
                     "packages/desktop_runtime/requirements.local.lock"):
            installer = [uv, "pip", "install", "--python", str(python)] if uv else [str(python), "-m", "pip", "install"]
            subprocess.run([*installer, "--require-hashes", "-r", lock], cwd=ROOT, check=True)
        marker.write_text(identity)
        result = subprocess.run([str(python), str(Path(__file__).resolve()), *sys.argv[1:]], cwd=ROOT, check=False)
    except (OSError, subprocess.CalledProcessError):
        raise SystemExit("Your desktop Python setup failed. Fix the installer error, then rerun `node scripts/desktop/prepare_local_stack.cjs`.") from None
    raise SystemExit(result.returncode)


