PRIVATE_NAMES = {"credentials.json", "secrets.json", "sessions", "__pycache__", ".git", ".venv", "node_modules", ".next"}


def private(path: Path) -> bool:
    return ("knowledge" in path.parts and path.name.endswith(".json.gz")
            and path.name not in {"startup_pmf.json.gz", "yc_video_advice.json.gz"}) or any(part in PRIVATE_NAMES or part == ".env" or part.startswith(".env.") for part in path.parts) or path.suffix in {
        ".db", ".sqlite", ".sqlite3", ".sqlite3-wal", ".sqlite3-shm", ".env", ".key", ".pem", ".p12", ".pfx", ".log", ".pyc", ".pth",
    }


def source_files(source: Path):
    if source.is_symlink():
        return
    if source.is_file():
        if not source.is_symlink() and not private(source):
            yield source
        return
    excluded = {"data", "tests", "fixtures"}
    if source == ROOT / "config":
        excluded.add("scaffold")
    for directory, directories, files in os.walk(source):
        parent = Path(directory)
        directories[:] = sorted(name for name in directories
                                if name not in excluded
                                and not private(parent.relative_to(source) / name)
                                and not (parent / name).is_symlink())
        for name in sorted(files):
            path = parent / name
            if path.is_file() and not path.is_symlink() and not private(path.relative_to(source)):
                yield path


def source_digest(sources: list[Path]) -> str:
    digest = hashlib.sha256()
    for source in sources:
        for path in source_files(source):
            digest.update(str(path).encode())
            digest.update(b"\0")
            digest.update(path.read_bytes())
            digest.update(b"\0")
    return digest.hexdigest()


def copy_source(source: Path, destination: Path) -> None:
    for path in source_files(source):
        relative = path.relative_to(source)
        target = destination / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        if path == ROOT / "config/hosts.json":
            try:
                hosts = json.loads(path.read_text(encoding="utf-8"))
                if not isinstance(hosts, dict) or not isinstance(hosts.get("local"), dict):
                    raise ValueError("Missing local host configuration")
            except ValueError:
                raise SystemExit("Restore the local entries in config/hosts.json from your source release, then rerun ./start --build.") from None
            target.write_text(json.dumps({"local": hosts["local"]}, indent=2) + "\n", encoding="utf-8")
        else:
            shutil.copy2(path, target)


def copy_dependencies(destination: Path) -> list[dict[str, str]]:
    pending = [Requirement(value.strip()) for value in
               (ROOT / "services/company_os/requirements.runtime.in").read_text().splitlines()
               if value.strip() and not value.startswith("#")]
    pending.extend(Requirement(value) for value in tomllib.loads(
        (ROOT / "services/company_os/pyproject.toml").read_text())["project"]["dependencies"])
    pending.append(Requirement("desktop-runtime[local-stack]"))
    projects = [tomllib.loads(path.read_text())["project"] for path in (ROOT / "packages").glob("*/pyproject.toml")]
    local = {project["name"].lower().replace("_", "-"): project for project in projects}
    seen: set[tuple[str, tuple[str, ...]]] = set()
    inventory: dict[str, str] = {}
    site = Path(sysconfig.get_path("purelib")).resolve()
    while pending:
        requirement = pending.pop()
        key = (requirement.name.lower().replace("_", "-"), tuple(sorted(requirement.extras)))
        if key in seen or (requirement.marker and not requirement.marker.evaluate()):
            continue
        seen.add(key)
        project = local.get(key[0])
        distribution = None if project else metadata.distribution(requirement.name)
        inventory[project["name"] if project else distribution.metadata["Name"]] = project["version"] if project else distribution.version
        for entry in distribution.files or () if distribution else ():
            source = Path(distribution.locate_file(entry)).resolve()
            if not source.is_relative_to(site) or not source.is_file():
                continue
            relative = source.relative_to(site)
            if (private(relative) and relative.as_posix() != "certifi/cacert.pem") or relative.name.startswith("__editable__"):
                continue
            target = destination / relative
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(source, target)
        dependencies = list(project.get("dependencies", []) if project else distribution.requires or ())
        if project:
            for extra in requirement.extras:
                dependencies.extend(project.get("optional-dependencies", {}).get(extra, []))
        for value in dependencies:
            dependency = Requirement(value)
            if dependency.marker and not any(dependency.marker.evaluate({"extra": extra})
                                             for extra in {"", *requirement.extras}):
                continue
            dependency.marker = None
            pending.append(dependency)
    return [{"name": name, "version": version} for name, version in sorted(inventory.items())]


def node_cache_dir() -> Path:
    if sys.platform == "darwin":
        return Path.home() / "Library/Caches/desktop-runtime/node"
    if sys.platform == "win32":
        return Path(os.environ.get("LOCALAPPDATA", Path.home() / "AppData/Local")) / "desktop-runtime/node"
    return Path(os.environ.get("XDG_CACHE_HOME", Path.home() / ".cache")) / "desktop-runtime/node"


def standalone_node(target: str) -> Path:
    platforms = {"apple-darwin": "darwin", "unknown-linux-gnu": "linux", "pc-windows-msvc": "win"}
    architecture, separator, platform_name = target.partition("-")
    if not separator or architecture not in {"aarch64", "x86_64"} or platform_name not in platforms:
        raise SystemExit(f"Your Node runtime does not support {target}. Use an arm64 or x64 Mac, Linux or Windows build, then rerun ./start.")
    system = platforms[platform_name]
    name = f"node-v{NODE_VERSION}-{system}-{'arm64' if architecture == 'aarch64' else 'x64'}"
    filename = name + (".zip" if system == "win" else ".tar.gz")
    try:
        checksums = dict(line.split(maxsplit=1)[::-1] for line in NODE_SHASUMS.read_text().splitlines() if line.strip())
        expected = checksums[filename]
        if not re.fullmatch(r"[a-f0-9]{64}", expected):
            raise ValueError("invalid SHA-256")
    except (OSError, KeyError, ValueError):
        raise SystemExit(f"Your pinned Node checksum for {filename} is missing or invalid. Save the official Node v{NODE_VERSION} SHASUMS256.txt from nodejs.org as {NODE_SHASUMS}, then rerun ./start.") from None
    cache = node_cache_dir()
    cache.mkdir(parents=True, exist_ok=True, mode=0o700)
    if cache.is_symlink():
        raise SystemExit(f"Your Node cache must be a regular folder. Choose a private cache folder instead of {cache}, then rerun ./start.")
    cache.chmod(0o700)
    archive = cache / filename
    if archive.is_symlink():
        raise SystemExit(f"Your Node cache archive must be a regular file. Remove {archive}, then rerun ./start.")
    with tempfile.TemporaryDirectory(dir=cache) as temporary:
        temporary = Path(temporary)
        download = temporary / filename
        if not archive.is_file():
            try:
                with urllib.request.urlopen(f"https://nodejs.org/dist/v{NODE_VERSION}/{filename}", timeout=120) as response, download.open("wb") as output:
                    shutil.copyfileobj(response, output)
            except (OSError, urllib.error.URLError):
                raise SystemExit(f"Your standalone Node runtime is not cached and could not be downloaded. Connect to the internet, then rerun ./start to download {filename}. Your existing work is retained.") from None
        source = archive if archive.is_file() else download
        with source.open("rb") as stream:
            actual = hashlib.file_digest(stream, "sha256").hexdigest()
        if actual != expected:
            raise SystemExit(f"Your Node archive failed SHA-256 verification: {filename} (expected {expected}, got {actual}). Remove {archive} if it exists, then rerun ./start while online.")
        if source == download:
            download.replace(archive)
        executable = "node.exe" if system == "win" else "bin/node"
        extracted = temporary / name
        try:
            if system == "win":
                with zipfile.ZipFile(archive) as distribution:
                    for member in (executable, "LICENSE"):
                        info = distribution.getinfo(f"{name}/{member}")
                        if info.is_dir() or (info.external_attr >> 16) & 0o170000 == 0o120000:
                            raise ValueError("runtime member is not a regular file")
                        destination = extracted / member
                        destination.parent.mkdir(parents=True, exist_ok=True)
                        with distribution.open(info) as source, destination.open("wb") as output:
                            shutil.copyfileobj(source, output)
            else:
                with tarfile.open(archive) as distribution:
                    for member in (executable, "LICENSE"):
                        info = distribution.getmember(f"{name}/{member}")
                        if not info.isfile():
                            raise ValueError("runtime member is not a regular file")
                        destination = extracted / member
                        destination.parent.mkdir(parents=True, exist_ok=True)
                        with distribution.extractfile(info) as source, destination.open("wb") as output:
                            shutil.copyfileobj(source, output)
        except (OSError, KeyError, ValueError, tarfile.TarError, zipfile.BadZipFile) as error:
            raise SystemExit(f"Your verified Node archive could not be unpacked: {error}. Remove {archive}, then rerun ./start while online.") from None
        (extracted / executable).chmod(0o755)
        destination = cache / name
        for directory in (destination, (destination / executable).parent):
            if directory.is_symlink() or (directory.exists() and not directory.is_dir()):
                raise SystemExit(f"Your extracted Node cache must be a regular folder. Remove {directory}, then rerun ./start.")
            directory.mkdir(parents=True, exist_ok=True)
        for member in (executable, "LICENSE"):
            (extracted / member).replace(destination / member)
    return destination / executable


