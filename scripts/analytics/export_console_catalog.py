#!/usr/bin/env python3
"""Write the console copy of the feature catalog: apps/console/src/lib/featureCatalog.ts.

The console and the desktop shell send only labels that appear here; a console test
(featureCatalog.test.ts) checks every route and tagged control against it, and
tests/unit/analytics/test_console_catalog.py fails when this file is stale.
Run: python3 scripts/analytics/export_console_catalog.py
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
TARGET = ROOT / "apps/console/src/lib/featureCatalog.ts"


def build() -> dict:
    sys.path[:0] = [str(ROOT / "services/company_os"), str(ROOT / "packages")]
    from app.analytics import feature_catalog as c
    from app.analytics.control_catalog import CONTROL_FEATURE

    return {
        "features": sorted(c.INGEST_FEATURES),
        # control id -> [slug, legacy group or null]; the label sent for a control is the legacy group when
        # one exists (unchanged history), else the slug.
        "controls": {k: [v, CONTROL_FEATURE.get(k)] for k, v in sorted(c.CONTROL_SLUG.items())},
        # route template prefix (ids as {}) -> slug, longest first, same order as route_feature().
        "routes": [[prefix, slug] for prefix, slug in c._ROUTE_ORDER],
    }


def render(catalog: dict) -> str:
    return (
        "// Generated by scripts/analytics/export_console_catalog.py from the server feature catalog. Do not edit.\n"
        "export const CATALOG: {\n  features: string[];\n  controls: Record<string, [string, string | null]>;\n"
        "  routes: [string, string][];\n} = " + json.dumps(catalog, indent=1) + ";\n"
    )


if __name__ == "__main__":
    TARGET.write_text(render(build()))
    print(f"wrote {TARGET}")
