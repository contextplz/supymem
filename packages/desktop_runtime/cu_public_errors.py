def public_failure_code(value, fallback: str) -> str:
    return value if isinstance(value, str) and value in PUBLIC_FAILURE_CODES else fallback


def public_exception_code(error: BaseException, fallback: str) -> str:
    try:
        return public_failure_code(str(error), fallback)
    except Exception:
        return fallback


def public_exception_type(error: BaseException) -> str:
    # Arbitrary plugin exception class names can themselves contain private data.
    name = type(error).__name__
    return name if name in PUBLIC_EXCEPTION_TYPES else "Exception"


def safe_exception_details(value) -> dict:
    if not isinstance(value, dict):
        return {}
    result = {}
    if isinstance(value.get("exception_type"), str) and value["exception_type"] in PUBLIC_EXCEPTION_TYPES:
        result["exception_type"] = value["exception_type"]
    location = value.get("exception_location")
    if isinstance(location, str) and len(location) <= 200 and re.fullmatch(
            r"(?:app|desktop_runtime|core|llm_gateway)(?:\.[a-zA-Z_][a-zA-Z_0-9]*)+:[1-9][0-9]{0,6}", location):
        result["exception_location"] = location
    if isinstance(value.get("exception_code"), str) and value["exception_code"] in PUBLIC_FAILURE_CODES:
        result["exception_code"] = value["exception_code"]
    frames = value.get("exception_frames")
    if isinstance(frames, list):
        frames = [frame for frame in frames if _safe_exception_frame(frame)]
        if frames:
            result["exception_frames"] = frames
    return result


def _safe_exception_frame(value) -> bool:
    if not isinstance(value, str) or len(value) > 200 or not re.fullmatch(
            r"[a-zA-Z_][a-zA-Z_0-9]*(?:\.[a-zA-Z_][a-zA-Z_0-9]*)*:[1-9][0-9]{0,6}", value):
        return False
    module = value.partition(":")[0]
    return module.partition(".")[0] in {"app", "desktop_runtime", "core", "llm_gateway", "coding_agents", "external"} | sys.stdlib_module_names


def public_exception_details(error: BaseException) -> dict:
    details = {"exception_type": public_exception_type(error)}
    try:
        details["exception_code"] = public_failure_code(str(error).partition(":")[0], "native_execution_failed")
    except Exception:
        details["exception_code"] = "native_execution_failed"
    frames, seen = [], set()
    current = error
    while current is not None and id(current) not in seen:
        seen.add(id(current))
        trace = current.__traceback__
        while trace is not None:
            location = f"{trace.tb_frame.f_globals.get('__name__', '')}:{trace.tb_lineno}"
            if current is error and safe_exception_details({"exception_location": location}):
                details["exception_location"] = location
            frames.append(location if _safe_exception_frame(location) else f"external:{trace.tb_lineno}")
            trace = trace.tb_next
        current = current.__cause__ or current.__context__
    if frames:
        details["exception_frames"] = frames
    return safe_exception_details(details)
