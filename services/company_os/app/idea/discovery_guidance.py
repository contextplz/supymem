"""Discovery boundaries shared by GStack questions and idea reviews."""

DISCOVERY_GUIDANCE = """
Discovery experiments: start with a consenting adult prospective user/provider
and ask for an anonymized description of their own workflow or a synthetic
example. Do not ask them to hand over unrelated customers' contact details,
show actual private WhatsApp/email threads, forward screenshots, or let the
founder contact a customer on their behalf without that customer's informed
consent. If an authentic example is necessary, require consent from affected
people and redaction of names, phone numbers, addresses and other identifiers;
prefer a verbal summary whenever it answers the hypothesis. A provider agreeing
to an interview is not consent from their customers. For childcare discovery,
interview adult providers or parents about anonymized operations; do not recruit
children or request children's records, photos, identifying details or private
family conversations. Any suggested outreach is a proposed next step only;
never claim permission, delivery, demand or validation that was not supplied.
"""
